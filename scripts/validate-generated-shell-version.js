#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path'),{execFileSync}=require('node:child_process');
const {ensureGeneratedShellVersion}=require('./version-generated-shell');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'ns-shell-version-'));
const git=args=>execFileSync('git',args,{cwd:root,stdio:['ignore','pipe','pipe']});
const files=['app-version.json','index.html','service-worker.js'];
try{
 fs.mkdirSync(path.join(root,'assets/js'),{recursive:true});
 for(const file of files)fs.copyFileSync(path.join(__dirname,'..',file),path.join(root,file));
 fs.writeFileSync(path.join(root,'assets/js/app-shell-runtime.js'),'old ranks');
 git(['init','--quiet']);git(['add','.']);git(['-c','user.name=QA','-c','user.email=qa@example.invalid','commit','--quiet','-m','Synthetic baseline']);
 const before=new Map(files.map(file=>[file,fs.readFileSync(path.join(root,file),'utf8')]));
 const previous=JSON.parse(before.get(files[0])).version;
 assert.equal(ensureGeneratedShellVersion({root}).changed,false,'identical generated bytes keep every cache key');
 fs.writeFileSync(path.join(root,'assets/js/app-shell-runtime.js'),'new ranks and actual observation');
 fs.writeFileSync(path.join(root,'index.html'),'<!-- unrelated pending edit -->\n'+before.get('index.html'));
 const pending=new Map(files.map(file=>[file,fs.readFileSync(path.join(root,file),'utf8')]));
 assert.throws(()=>ensureGeneratedShellVersion({root}),/Pending shell edits/,'unrelated unversioned page edits cannot enter an automated data release');
 for(const [file,bytes] of pending)assert.equal(fs.readFileSync(path.join(root,file),'utf8'),bytes);
 fs.writeFileSync(path.join(root,'index.html'),before.get('index.html'));
 const result=ensureGeneratedShellVersion({root});assert.equal(result.version,String(Number(previous)+1));
 const html=fs.readFileSync(path.join(root,'index.html'),'utf8'),worker=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
 const asset=html.match(/<script src="(assets\/js\/app-shell-runtime\.js\?v=\d+)"/)[1];
 assert(worker.includes('"/'+asset+'"'),'fresh page and required worker cache use the same new script key');
 assert(!worker.includes('/assets/js/app-shell-runtime.js?v='+previous+'"'),'old cached script cannot satisfy the new required key');
 assert(worker.includes('const SHELL_VERSION = "'+result.version+'";'),'installed page gets an actual forward upgrade');
 assert(html.includes('assets/js/app-update.js?v=293'),'unrelated script versions remain intact');
 const once=new Map(files.map(file=>[file,fs.readFileSync(path.join(root,file),'utf8')]));
 assert.equal(ensureGeneratedShellVersion({root}).reason,'already versioned','a repeated pre-commit invocation does not bump twice');
 for(const [file,bytes] of once)assert.equal(fs.readFileSync(path.join(root,file),'utf8'),bytes);
 fs.writeFileSync(path.join(root,'service-worker.js'),worker.replace('const SHELL_VERSION = "'+result.version+'";','const SHELL_VERSION = "0";'));
 const invalid=new Map(files.map(file=>[file,fs.readFileSync(path.join(root,file),'utf8')]));
 assert.throws(()=>ensureGeneratedShellVersion({root}),/inconsistent/,'inconsistent manual versions fail before any write');
 for(const [file,bytes] of invalid)assert.equal(fs.readFileSync(path.join(root,file),'utf8'),bytes);
 const release=fs.readFileSync(path.join(__dirname,'redeploy-and-release.sh'),'utf8');
 const main=release.slice(release.indexOf('INITIAL_HEAD='));
 for(const file of files)assert(main.includes('"'+file+'"'),'generated cache changes are published with their runtime');
 assert(main.includes('if ! git diff --quiet HEAD -- assets/js/app-shell-runtime.js; then\n  CARD_OUTPUT_FILES+='),'unchanged runtimes cannot stage unrelated shell edits');
 assert(main.indexOf('node scripts/version-generated-shell.js')<main.indexOf('git add "${CARD_OUTPUT_FILES[@]}"'),'versioning precedes the release commit');
 assert(main.indexOf('node scripts/validate-shell-script-cache.js')<main.indexOf('git add "${CARD_OUTPUT_FILES[@]}"'),'cache validation precedes publication');
 console.log('Generated shell: no-op, forward keys/worker, idempotence, inconsistent-input retention and release integration passed.');
}finally{fs.rmSync(root,{recursive:true,force:true});}
