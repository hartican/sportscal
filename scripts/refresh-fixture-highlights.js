'use strict';
// Source/projection step owned exclusively by update-cards.js, including quick.
const fs=require('node:fs'),crypto=require('node:crypto'),media=require('../lib/fixture-highlights'),identity=require('../config/fixture-identity');
const CACHE='data/canonical/fixture-highlights.v1.json';
function apply(records,now=new Date()){
  let count=0;
  for(const file of ['feeds/incoming/events.json','data/events.json']){
    const document=JSON.parse(fs.readFileSync(file,'utf8'));
    const events=media.applyCached(document.events,records,now);
    const changed=events.filter((e,i)=>JSON.stringify(e.highlights)!==JSON.stringify(document.events[i]?.highlights)).length;
    if(changed){
      const hash=crypto.createHash('sha256').update(JSON.stringify(events.filter(e=>e.highlights!==undefined).map(e=>[e.id,e.highlights]))).digest('hex').slice(0,12);
      const next={...document,events,version:document.version.replace(/-highlights-[a-f0-9]{12}$/,'')+'-highlights-'+hash,publishedAt:new Date().toISOString()};
      const errors=require('./lib/feed-utils').validateFeed(next);if(errors.length)throw Error('Invalid highlights projection: '+errors.join('; '));
      fs.writeFileSync(file,JSON.stringify(next,null,2)+'\n');count+=changed;
      if(file==='data/events.json'){
        fs.writeFileSync('data/events.js','/* Generated by canonical fixture highlights projection. Do not edit directly. */\nglobalThis.NOTHINGSPORTS_EVENTS = '+JSON.stringify(events,null,2)+';\n');
        const meta=JSON.parse(fs.readFileSync('data/feed-meta.json','utf8'));fs.writeFileSync('data/feed-meta.json',JSON.stringify({...meta,version:next.version,publishedAt:next.publishedAt},null,2)+'\n');
      }
    }
  }
  return count;
}
async function refresh({offline=false,now=new Date(),fetchImpl=globalThis.fetch,records}={}){
  const previous=JSON.parse(fs.readFileSync(CACHE,'utf8'));
  let failed=false;
  if(!records&&!offline)try{
    const feed=JSON.parse(fs.readFileSync('feeds/incoming/events.json','utf8')).events;
    const schedule=JSON.parse(fs.readFileSync('data/follow-schedule/tennis.json','utf8')).fixtures.map(e=>identity.fromSchedule(e,{slug:'tennis'}));
    records=await media.refresh({events:identity.mergeOverlays(schedule,feed),previous:previous.events,now,fetchImpl,signal:AbortSignal.timeout(20000),apiKey:process.env.YOUTUBE_DATA_API_KEY||'',searchBudget:0});
    failed=Boolean(records.coverage?.failures?.length);
  }catch{failed=true;}
  const events=media.expireRecords(records?require('../lib/fixture-snapshot').mergeFixtureSnapshot(previous.events,records).events:previous.events,now);
  if(JSON.stringify(events)!==JSON.stringify(previous.events))fs.writeFileSync(CACHE,JSON.stringify({...previous,events},null,2)+'\n');
  const changed=apply(events,now);return {changed,linked:events.filter(e=>e.highlights).length,failed,mode:process.env.YOUTUBE_DATA_API_KEY?'public-feeds-with-api-fallback':'public-feeds'};
}
if(require.main===module)refresh({offline:process.argv.includes('--offline')}).then(r=>console.log(JSON.stringify(r))).catch(()=>{console.error('Highlights projection failed');process.exitCode=1;});
module.exports={refresh,apply,CACHE};
