function readJson(filePath){
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function sydneyDateKey(value){
  const dateKey = jointTennis.zonedDateKey(value, SYDNEY_TIME_ZONE);
  if (!dateKey) throw new TypeError(`Invalid tournament check time: ${value}`);
  return dateKey;
}

function tournamentLocalDateKey(value, tournament){
  const dateKey = jointTennis.zonedDateKey(value, tournament?.timezone);
  if (!dateKey) throw new TypeError(`Invalid tournament check time: ${value}`);
  return dateKey;
}

function dateIsInsideTournament(dateKey, tournament){
  return Boolean(dateKey && tournament?.startDate && tournament?.endDate
    && dateKey >= tournament.startDate && dateKey <= tournament.endDate);
}

function tournamentRefreshIsActive(tournament, value){
  const localDate = tournamentLocalDateKey(value, tournament);
  // At 9am Sydney, Ohio is on the prior evening. The Sydney date is therefore
  // the upcoming Cincinnati order-of-play day and lets the first OOP be found.
  const upcomingOrderDate = sydneyDateKey(value);
  return dateIsInsideTournament(localDate, tournament)
    || dateIsInsideTournament(upcomingOrderDate, tournament);
}

