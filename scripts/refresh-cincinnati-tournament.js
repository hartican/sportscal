function integrityError(code, message){
  const error = new Error(message);
  error.code = `integrity_${code}`;
  return error;
}

function contentSignature(document){
  if (!document) return "";
  const comparable = JSON.parse(JSON.stringify(document));
  delete comparable.retrievedAt;
  if (comparable.freshness) {
    delete comparable.freshness.lastSuccessfulAt;
    delete comparable.freshness.ageHours;
    delete comparable.freshness.failureCode;
  }
  if (comparable.resultAvailability) delete comparable.resultAvailability.checkedAt;
  comparable.sourceDocuments = (comparable.sourceDocuments || []).filter(source => source.kind === "order_of_play").map(source => {
    delete source.retrievedAt;
    delete source.sha256;
    return source;
  });
  return crypto.createHash("sha256").update(JSON.stringify(comparable)).digest("hex");
}

function htmlEntities(value){
  return String(value || "")
    .replace(/&amp;/gi, "&")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">");
}

function assertApprovedPublisherPage(pageUrl){
  if (!Object.values(OFFICIAL_PAGES).includes(pageUrl)) throw new Error(`Unapproved Cincinnati publisher page: ${pageUrl}`);
  return pageUrl;
}

function assertApprovedPublishedDocument(record){
  assertApprovedPublisherPage(record?.publisherPageUrl);
  const source = new URL(record?.sourceUrl);
  if (source.protocol !== "https:") throw new Error(`Cincinnati documents must use HTTPS: ${source.href}`);
  if (BLOCKED_AUTOMATION_HOSTS.test(source.hostname)) throw new Error(`ATP, WTA, Rain and paid-provider fallbacks are not approved for automation: ${source.hostname}`);
  if (!/\.pdf(?:$|[?#])/i.test(source.href)) throw new Error(`Only published Cincinnati PDF documents may be followed: ${source.href}`);
  return record;
}

function discoverPublishedDocuments(html, publisherPageUrl, kind){
  assertApprovedPublisherPage(publisherPageUrl);
  const seen = new Set();
  const output = [];
  const addCandidate = rawHref => {
    let sourceUrl;
    try {
      sourceUrl = new URL(htmlEntities(rawHref), publisherPageUrl).href;
    } catch (_error) {
      return;
    }
    if (!/\.pdf(?:$|[?#])/i.test(sourceUrl) || seen.has(sourceUrl)) return;
    const record = { kind, publisherPageUrl, sourceUrl };
    assertApprovedPublishedDocument(record);
    seen.add(sourceUrl);
    output.push(record);
  };
  const hrefPattern = /\bhref\s*=\s*(?:"([^"]+)"|'([^']+)'|([^\s>]+))/gi;
  let match;
  while ((match = hrefPattern.exec(String(html || "")))) {
    addCandidate(match[1] || match[2] || match[3]);
  }
  const decodedPage = String(html || "").replace(/\\\//g, "/");
  const embeddedPdfPattern = /(?:https?:\/\/|\/)[^\s"'<>]+\.pdf(?:[?#][^\s"'<>]*)?/gi;
  while ((match = embeddedPdfPattern.exec(decodedPage))) addCandidate(match[0]);
  return output;
}

function jsonLdSportsEvents(html){
  const events = [];
  const visit = value => {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (!value || typeof value !== "object") return;
    const types = Array.isArray(value["@type"]) ? value["@type"] : [value["@type"]];
    if (types.some(type => String(type || "").toLowerCase() === "sportsevent")) events.push(value);
    if (value["@graph"]) visit(value["@graph"]);
  };
  const scriptPattern = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
  let script;
  while ((script = scriptPattern.exec(String(html || "")))) {
    if (!/\btype\s*=\s*(?:"application\/ld\+json"|'application\/ld\+json'|application\/ld\+json)/i.test(script[1])) continue;
    try {
      visit(JSON.parse(script[2].trim()));
    } catch (_error) {
      // Invalid or unrelated page metadata is not a result. Never infer from it.
    }
  }
  return events;
}

function schemaName(value){
  if (typeof value === "string") return value.trim();
  if (value && typeof value === "object" && typeof value.name === "string") return value.name.trim();
  return "";
}

function completedSportsEvent(event){
  const status = typeof event?.eventStatus === "string" ? event.eventStatus : event?.eventStatus?.["@id"];
  return /(?:^|\/)EventCompleted$/i.test(String(status || ""));
}

function extractOfficialResultsHtml(html, { document, publisherPageUrl, retrievedAt }){
  const approvedPageUrl = assertApprovedPublisherPage(publisherPageUrl);
  const addressable = Array.from(new Map([
    ...(document?.schedule?.matches || []),
    ...(document?.matchHistory || []),
  ].map(match => [match.matchId, match])).values());
  const matchesByPair = new Map();
  addressable.forEach(match => {
    const pairKey = match.players.map(player => jointTennis.slug(player.name)).sort().join("|");
    const candidates = matchesByPair.get(pairKey) || [];
    candidates.push(match);
    matchesByPair.set(pairKey, candidates);
  });
  const results = {};
  jsonLdSportsEvents(html).forEach(event => {
    if (!completedSportsEvent(event) || jointTennis.slug(schemaName(event.sport)) !== "tennis") return;
    const competitors = Array.isArray(event.competitor) ? event.competitor : event.competitor ? [event.competitor] : [event.homeTeam, event.awayTeam].filter(Boolean);
    const competitorNames = competitors.map(schemaName).filter(Boolean);
    if (competitorNames.length !== 2 || new Set(competitorNames.map(jointTennis.slug)).size !== 2) return;
    const candidates = matchesByPair.get(competitorNames.map(jointTennis.slug).sort().join("|")) || [];
    if (candidates.length !== 1) return;
    const match = candidates[0];
    const winnerName = schemaName(event.winner);
    const winner = match.players.find(player => jointTennis.slug(player.name) === jointTennis.slug(winnerName));
    const score = typeof event.score === "string" ? event.score : typeof event.result === "string" ? event.result : "";
    if (!winner || !/(?:^|\s)[0-7][-–][0-7](?:\(\d+\))?(?=\s|$)/.test(score.trim())) return;
    const result = {
      status: "completed",
      score: score.replace(/\s+/g, " ").trim(),
      winnerPlayerId: winner.playerId,
      sourceUrl: approvedPageUrl,
      retrievedAt,
    };
    const existing = results[match.matchId];
    if (existing && (existing.score !== result.score || existing.winnerPlayerId !== result.winnerPlayerId)) {
      throw integrityError("conflicting_results", `Official Cincinnati result records conflict for ${match.matchId}`);
    }
    results[match.matchId] = result;
  });
  return results;
}

function decodePdfLiteral(value){
  return String(value || "").replace(/\\([0-7]{1,3}|[nrtbf()\\])/g, (_match, escape) => {
    if (/^[0-7]/.test(escape)) return String.fromCharCode(parseInt(escape, 8));
    return { n: "\n", r: "\r", t: "\t", b: "\b", f: "\f", "(": "(", ")": ")", "\\": "\\" }[escape] || escape;
  });
}

function textFromPdfContent(content){
  const lines = [];
  const textOperator = /\(((?:\\.|[^\\()])*)\)\s*(?:Tj|'|")/g;
  let match;
  while ((match = textOperator.exec(content))) lines.push(decodePdfLiteral(match[1]));
  const arrayOperator = /\[((?:.|\r|\n)*?)\]\s*TJ/g;
  while ((match = arrayOperator.exec(content))) {
    const fragments = [];
    const fragmentPattern = /\(((?:\\.|[^\\()])*)\)/g;
    let fragment;
    while ((fragment = fragmentPattern.exec(match[1]))) fragments.push(decodePdfLiteral(fragment[1]));
    if (fragments.length) lines.push(fragments.join(""));
  }
  return lines;
}

function positionedTextFromPdfContent(content){
  const rows = [];
  let currentX = null;
  let currentY = null;
  const tokenPattern = /(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+Tm|\(((?:\\.|[^\\()])*)\)\s*Tj|\[((?:.|\r|\n)*?)\]\s*TJ/g;
  let token;
  while ((token = tokenPattern.exec(content))) {
    if (token[1] != null) {
      currentX = Number(token[5]);
      currentY = Number(token[6]);
      continue;
    }
    if (!Number.isFinite(currentX) || !Number.isFinite(currentY)) continue;
    let value = token[7] != null ? decodePdfLiteral(token[7]) : "";
    if (token[8] != null) {
      const fragments = [];
      const fragmentPattern = /\(((?:\\.|[^\\()])*)\)/g;
      let fragment;
      while ((fragment = fragmentPattern.exec(token[8]))) fragments.push(decodePdfLiteral(fragment[1]));
      value = fragments.join("");
    }
    value = value.replace(/\s+/g, " ").trim();
    if (value) rows.push({ x: currentX, y: currentY, value });
  }
  if (!rows.length) return [];
  const grouped = [];
  rows.slice().sort((first, second) => second.y - first.y || first.x - second.x).forEach(item => {
    let row = grouped.find(candidate => Math.abs(candidate.y - item.y) <= 1.5);
    if (!row) {
      row = { y: item.y, cells: [] };
      grouped.push(row);
    }
    row.cells.push(item);
  });
  return grouped.sort((first, second) => second.y - first.y).map(row => {
    const cells = row.cells.sort((first, second) => first.x - second.x);
    let output = "";
    let previousX = null;
    cells.forEach(cell => {
      const separator = previousX == null ? "" : cell.x - previousX > 48 ? " | " : " ";
      output += `${separator}${cell.value}`;
      previousX = cell.x;
    });
    return output.trim();
  }).filter(Boolean);
}

function extractPdfTextWithPdfKit(buffer){
  if (process.platform !== "darwin" || !fs.existsSync("/usr/bin/osascript")) return "";
  const temporaryDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "nothingsport-cincinnati-pdf-"));
  const pdfPath = path.join(temporaryDirectory, "order-of-play.pdf");
  try {
    fs.writeFileSync(pdfPath, buffer);
    const script = [
      "ObjC.import('PDFKit');",
      "ObjC.import('Foundation');",
      "function run(argv){",
      "  const url = $.NSURL.fileURLWithPath(argv[0]);",
      "  const document = $.PDFDocument.alloc.initWithURL(url);",
      "  if (!document) return '';",
      "  return ObjC.unwrap(document.string || '');",
      "}",
    ].join("\n");
    const result = spawnSync("/usr/bin/osascript", ["-l", "JavaScript", "-e", script, pdfPath], {
      encoding: "utf8",
      maxBuffer: 16 * 1024 * 1024,
      timeout: 20000,
    });
    return result.status === 0 ? String(result.stdout || "").trim() : "";
  } catch (_error) {
    return "";
  } finally {
    fs.rmSync(temporaryDirectory, { recursive: true, force: true });
  }
}

function extractPdfText(input){
  const buffer = Buffer.isBuffer(input) ? input : Buffer.from(input);
  const binary = buffer.toString("latin1");
  const lines = [];
  const streamPattern = /stream\r?\n([\s\S]*?)\r?\nendstream/g;
  let streamMatch;
  while ((streamMatch = streamPattern.exec(binary))) {
    const header = binary.slice(Math.max(0, streamMatch.index - 300), streamMatch.index);
    let streamBuffer = Buffer.from(streamMatch[1], "latin1");
    if (/\/FlateDecode\b/.test(header)) {
      try {
        streamBuffer = zlib.inflateSync(streamBuffer);
      } catch (_error) {
        continue;
      }
    }
    const content = streamBuffer.toString("latin1");
    const positioned = positionedTextFromPdfContent(content);
    lines.push(...(positioned.length >= 3 ? positioned : textFromPdfContent(content)));
  }
  if (!lines.length) lines.push(...textFromPdfContent(binary));
  const embeddedText = lines.map(line => line.replace(/\s+/g, " ").trim()).filter(Boolean).join("\n");
  if (embeddedText.split(/\r?\n/).some(parseScheduleDate)) return embeddedText;
  return extractPdfTextWithPdfKit(buffer) || embeddedText;
}

function parseScheduleDate(line){
  const match = String(line || "").match(/(?:MONDAY|TUESDAY|WEDNESDAY|THURSDAY|FRIDAY|SATURDAY|SUNDAY)?\s*,?\s*(\d{1,2})\s+(JANUARY|FEBRUARY|MARCH|APRIL|MAY|JUNE|JULY|AUGUST|SEPTEMBER|OCTOBER|NOVEMBER|DECEMBER)\s+(20\d{2})/i)
    || String(line || "").match(/(?:MONDAY|TUESDAY|WEDNESDAY|THURSDAY|FRIDAY|SATURDAY|SUNDAY)?\s*,?\s*(JANUARY|FEBRUARY|MARCH|APRIL|MAY|JUNE|JULY|AUGUST|SEPTEMBER|OCTOBER|NOVEMBER|DECEMBER)\s+(\d{1,2}),?\s+(20\d{2})/i);
  if (!match) return null;
  const monthFirst = Number.isNaN(Number(match[1]));
  const day = Number(monthFirst ? match[2] : match[1]);
  const month = MONTHS[String(monthFirst ? match[1] : match[2]).toLowerCase()];
  const year = Number(match[3]);
  const date = `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  const parsed = new Date(`${date}T00:00:00Z`);
  if (parsed.getUTCFullYear() !== year || parsed.getUTCMonth() + 1 !== month || parsed.getUTCDate() !== day) throw integrityError("impossible_date", `Impossible order-of-play date: ${line}`);
  return date;
}

function clock24(hourInput, minuteInput, suffixInput){
  let hour = Number(hourInput);
  const minute = Number(minuteInput || 0);
  const suffix = String(suffixInput || "").toUpperCase();
  if (suffix === "PM" && hour < 12) hour += 12;
  if (suffix === "AM" && hour === 12) hour = 0;
  if (hour > 23 || minute > 59) throw integrityError("impossible_time", `Impossible published match time: ${hourInput}:${minuteInput}`);
  return `${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}`;
}

function parseTiming(line){
  const normalized = String(line || "").replace(/\s+/g, " ").trim();
  if (/^FOLLOWED BY$/i.test(normalized)) return { type: "followed_by", label: "Followed by", localTime: null };
  if (/^(?:SESSION(?: ONLY)?|DAY SESSION|NIGHT SESSION)$/i.test(normalized)) return { type: "session_only", label: normalized.replace(/\b\w/g, letter => letter.toUpperCase()), localTime: null };
  const notBefore = normalized.match(/^NOT BEFORE\s+(\d{1,2})(?::(\d{2}))?\s*(AM|PM)?$/i);
  if (notBefore) return { type: "not_before", label: `Not before ${notBefore[1]}:${notBefore[2] || "00"}${notBefore[3] ? ` ${notBefore[3].toUpperCase()}` : ""}`, localTime: clock24(notBefore[1], notBefore[2], notBefore[3]) };
  const exact = normalized.match(/^(?:(?:STARTING|STARTS) AT:?\s+)?(\d{1,2})(?::(\d{2}))\s*(AM|PM)?$/i);
  if (exact) return { type: "exact", label: `${exact[1]}:${exact[2]}${exact[3] ? ` ${exact[3].toUpperCase()}` : ""}`, localTime: clock24(exact[1], exact[2], exact[3]) };
  return null;
}

function playerIndex(catalogue){
  const index = new Map();
  (catalogue?.athletes || []).forEach(player => {
    index.set(`${player.tour}:${jointTennis.slug(player.displayName)}`, player);
  });
  return index;
}

function parseParticipant(rawValue, tour, rankings){
  const countryMatches = Array.from(String(rawValue || "").matchAll(/\(([A-Z]{3})\)|(?:^|\s)([A-Z]{3})(?=\s*$)/g));
  if (countryMatches.length > 1) throw new Error(`Doubles participant is outside the singles card model: ${rawValue}`);
  const country = countryMatches[0]?.[1] || countryMatches[0]?.[2] || null;
  const cleanName = String(rawValue || "")
    .replace(/\s*\([A-Z]{3}\)\s*/g, " ")
    .replace(/\s*\[(?:\d+|WC|Q|LL|PR|ALT)\]\s*/gi, " ")
    .replace(/\s+[A-Z]{3}\s*$/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (cleanName.length < 2) throw new Error(`Could not parse tennis player: ${rawValue}`);
  const known = rankings.get(`${tour}:${jointTennis.slug(cleanName)}`);
  const knownNationalityCodes = new Set(Array.from(rankings.values()).map(player => player.nationalityCode).filter(Boolean));
  const embeddedCountryCode = (cleanName.match(/\b[A-Z]{3}\b/g) || []).some(code => knownNationalityCodes.has(code));
  if (!known && embeddedCountryCode) throw new Error(`Ambiguous multi-player side is outside the singles card model: ${rawValue}`);
  const nationalityCode = known?.nationalityCode || country;
  return {
    playerId: known?.athleteId || `competitor:tennis:${tour.toLowerCase()}:${jointTennis.slug(cleanName)}`,
    name: known?.displayName || cleanName,
    ranking: Number.isInteger(known?.rankingSingles) ? known.rankingSingles : null,
    nationalityCode: nationalityCode || null,
    isAustralian: nationalityCode === "AUS",
  };
}

function parseMatchLine(line, rankings){
  const normalized = String(line || "").replace(/\s+/g, " ").trim();
  const structured = normalized.match(/^(ATP|WTA)\s*\|\s*([^|]+?)\s*\|\s*(.+?)\s+(?:VS?\.?|V\.?)\s+(.+)$/i);
  let tour;
  let round = "unknown";
  let firstPlayer;
  let secondPlayer;
  if (structured) {
    tour = structured[1].toUpperCase();
    round = jointTennis.normalizeRound(structured[2]);
    firstPlayer = structured[3];
    secondPlayer = structured[4];
  } else {
    const prefixed = normalized.match(/^(ATP|WTA)\s+(.+?)\s+(?:VS?\.?|V\.?)\s+(.+)$/i);
    const suffixed = normalized.match(/^(.+?)\s+(?:VS?\.?|V\.?)\s+(.+?)\s+(ATP|WTA)$/i);
    if (prefixed) {
      tour = prefixed[1].toUpperCase();
      firstPlayer = prefixed[2];
      secondPlayer = prefixed[3];
    } else if (suffixed) {
      tour = suffixed[3].toUpperCase();
      firstPlayer = suffixed[1];
      secondPlayer = suffixed[2];
    } else {
      return null;
    }
  }
  if (/\bor\b/i.test(`${firstPlayer} ${secondPlayer}`)) return null;
  try {
    return {
      tour,
      round,
      players: [parseParticipant(firstPlayer, tour, rankings), parseParticipant(secondPlayer, tour, rankings)],
    };
  } catch (_error) {
    return null;
  }
}

function tableCells(line){
  const cells = String(line || "").split(/\s+\|\s+/).map(cell => cell.trim());
  return cells.length > 1 ? cells : cells.filter(Boolean);
}

function courtLabel(cell){
  const normalized = String(cell || "").replace(/^(?:REVISED\s+)+/i, "").replace(/\s+/g, " ").trim();
  if (!normalized || /ANY MATCH|PLAYERS['’]? LOUNGE|LOCKER-ROOM/i.test(normalized)) return null;
  if (!/(?:COURT|GRANDSTAND|STADIUM)/i.test(normalized)) return null;
  if (!/^(?:[A-Z0-9&'’.+-]+\s+){0,4}(?:COURT(?:\s+\d+)?|GRANDSTAND|STADIUM(?:\s+\d+)?)$/i.test(normalized)) return null;
  return normalized.toUpperCase();
}

function parseOrderOfPlayText(text, { tournament, catalogue }){
  const lines = String(text || "").split(/\r?\n/).map(line => line.replace(/\s+/g, " ").trim()).filter(Boolean);
  const rankings = playerIndex(catalogue);
  const courtCounts = new Map();
  const courtOrder = new Map();
  const orderOfPlayDate = lines
    .filter(line => /ORDER OF PLAY/i.test(line))
    .map(parseScheduleDate)
    .find(Boolean);
  let scheduleDate = orderOfPlayDate || lines.map(parseScheduleDate).find(Boolean) || null;
  let currentCourt = null;
  let currentTiming = null;
  let tableCourts = [];
  let tableTimings = [];
  let tableMatchIndex = 0;
  let matchesSinceCourtBlock = false;
  let pendingTour = null;
  let pendingFirstPlayer = null;
  let awaitingSecondPlayer = false;
  let columnBlockMatches = false;
  let scheduledSequence = 0;
  const matches = [];

  const appendParsedMatch = (parsedMatch, tableIndex = null) => {
    if (!scheduleDate) throw new Error("Order of play did not publish a parseable date before its matches");
    const tableCourt = Number.isInteger(tableIndex) && tableCourts.length
      ? tableCourts[tableIndex % tableCourts.length]
      : null;
    const assignedCourt = tableCourt || currentCourt;
    if (!assignedCourt) throw new Error("Order of play did not publish a court before a match");
    const courtSequence = (courtCounts.get(assignedCourt) || 0) + 1;
    courtCounts.set(assignedCourt, courtSequence);
    scheduledSequence += 1;
    const timingForMatch = (Number.isInteger(tableIndex) ? tableTimings[tableIndex] : null)
      || currentTiming
      || { type: "session_only", label: "Session only", localTime: null };
    const matchInput = {
      ...parsedMatch,
      venue: tournament.venue,
      court: assignedCourt,
      courtSequence,
      scheduledSequence,
      timing: timingForMatch,
      narrativeSignals: [],
    };
    matchInput.matchId = jointTennis.stableMatchId({ tournamentId: tournament.tournamentId, date: scheduleDate, tour: matchInput.tour, players: matchInput.players });
    matches.push(matchInput);
    matchesSinceCourtBlock = true;
    currentTiming = null;
  };

  lines.forEach(line => {
    const cells = tableCells(line);
    const courtsOnLine = cells.map(courtLabel).filter(Boolean);
    if (courtsOnLine.length) {
      if (matchesSinceCourtBlock) tableCourts = [];
      tableCourts.push(...courtsOnLine);
      tableCourts = Array.from(new Set(tableCourts));
      tableCourts.forEach(court => {
        if (!courtOrder.has(court)) courtOrder.set(court, courtOrder.size);
      });
      currentCourt = tableCourts[0];
      currentTiming = null;
      tableTimings = [];
      tableMatchIndex = 0;
      matchesSinceCourtBlock = false;
      pendingTour = null;
      pendingFirstPlayer = null;
      awaitingSecondPlayer = false;
      return;
    }
    const parsedTimings = cells.map(parseTiming);
    const timingsOnLine = parsedTimings.filter(Boolean);
    if (timingsOnLine.length) {
      if (tableCourts.length > 1 || cells.length > 1) tableTimings.push(...parsedTimings);
      currentTiming = timingsOnLine[0];
      return;
    }
    const standaloneTour = line.match(/^(ATP|WTA)$/i);
    if (standaloneTour) {
      pendingTour = standaloneTour[1].toUpperCase();
      pendingFirstPlayer = null;
      awaitingSecondPlayer = false;
      return;
    }
    if (pendingTour && !pendingFirstPlayer) {
      pendingFirstPlayer = line;
      return;
    }
    if (pendingTour && pendingFirstPlayer && /^VS?\.?$/i.test(line)) {
      awaitingSecondPlayer = true;
      return;
    }
    if (pendingTour && pendingFirstPlayer && awaitingSecondPlayer) {
      try {
        appendParsedMatch({
          tour: pendingTour,
          round: "unknown",
          players: [
            parseParticipant(pendingFirstPlayer, pendingTour, rankings),
            parseParticipant(line, pendingTour, rankings),
          ],
        });
        columnBlockMatches = true;
      } finally {
        pendingTour = null;
        pendingFirstPlayer = null;
        awaitingSecondPlayer = false;
      }
      return;
    }
    const structuredMatch = /^(?:ATP|WTA)\s*\|/i.test(line) ? parseMatchLine(line, rankings) : null;
    const rowStartIndex = tableMatchIndex;
    const matchCells = structuredMatch
      ? [{ parsedMatch: structuredMatch, tableIndex: rowStartIndex }]
      : (cells.length > 1 ? cells : [line])
        .map((cell, index) => ({ parsedMatch: parseMatchLine(cell, rankings), tableIndex: rowStartIndex + index }))
        .filter(entry => entry.parsedMatch);
    matchCells.forEach(({ parsedMatch, tableIndex }) => appendParsedMatch(parsedMatch, tableIndex));
    if (matchCells.length) tableMatchIndex += structuredMatch ? 1 : Math.max(tableCourts.length || 1, cells.length);
  });

  if (!scheduleDate) throw new Error("Order of play did not contain a supported calendar date");
  if (scheduleDate < tournament.startDate || scheduleDate > tournament.endDate) throw integrityError("impossible_date", `Order-of-play date ${scheduleDate} is outside the Cincinnati tournament window`);
  if (!matches.length) throw new Error("Order of play contained no parseable ATP/WTA singles matches");
  if (columnBlockMatches) {
    matches.sort((first, second) => (
      first.courtSequence - second.courtSequence
      || (courtOrder.get(first.court) || 0) - (courtOrder.get(second.court) || 0)
    ));
    matches.forEach((match, index) => { match.scheduledSequence = index + 1; });
  }
  const ids = matches.map(match => match.matchId);
  if (new Set(ids).size !== ids.length) throw integrityError("duplicate_match_ids", "Order of play generated duplicate stable match IDs");
  return { date: scheduleDate, matches };
}

function cincinnatiTournament(catalogue){
  const tournaments = (catalogue?.tournaments || []).filter(tournament => /cincinnati/i.test(tournament.name) && ["ATP", "WTA"].includes(tournament.tour));
  const tours = new Set(tournaments.map(tournament => tournament.tour));
  if (tours.size !== 2) throw new Error("The canonical tennis catalogue must contain Cincinnati ATP and WTA tournaments");
  const season = Number(tournaments[0].season);
  const officialWindow = season === 2026 ? CINCINNATI_2026_WINDOW : null;
  return {
    tournamentId: jointTennis.stableTournamentId({ name: "Cincinnati Open", season }),
    name: "Cincinnati Open",
    season,
    sportId: "sport:tennis",
    representedTours: ["ATP", "WTA"],
    venue: "Lindner Family Tennis Center",
    location: "Mason, Ohio, USA",
    timezone: "America/New_York",
    startDate: officialWindow?.startDate || tournaments.map(tournament => tournament.startDate).sort()[0],
    endDate: officialWindow?.endDate || tournaments.map(tournament => tournament.endDate).sort().at(-1),
  };
}

function sourceRecord(document, retrievedAt, buffer){
  return {
    ...document,
    retrievedAt,
    sha256: crypto.createHash("sha256").update(buffer).digest("hex"),
  };
}

function buildDocumentFromPdf({ pdfBuffer, sourceDocument, retrievedAt, catalogue }){
  assertApprovedPublishedDocument(sourceDocument);
  const tournament = cincinnatiTournament(catalogue);
  const parsed = parseOrderOfPlayText(extractPdfText(pdfBuffer), { tournament, catalogue });
  const matchesWithInstants = parsed.matches.map(match => ({
    ...match,
    scheduleDate: parsed.date,
    scheduledAtUtc: match.timing?.localTime
      ? jointTennis.zonedDateTimeToUtc(parsed.date, match.timing.localTime, tournament.timezone)
      : null,
  }));
  const selected = jointTennis.selectPromotedMatches(matchesWithInstants, 3);
  const promotedIds = new Set(selected.promotedMatchIds);
  const promotedMatches = selected.matches.filter(match => promotedIds.has(match.matchId));
  return {
    schemaVersion: jointTennis.SCHEMA_VERSION,
    tournament,
    retrievedAt,
    freshness: {
      confidence: jointTennis.aggregateConfidence(promotedMatches),
      mode: "schedule",
      lastSuccessfulAt: retrievedAt,
      staleAfterHours: MAX_STALE_HOURS,
    },
    sourcePages: Object.values(OFFICIAL_PAGES),
    sourceDocuments: [sourceRecord(sourceDocument, retrievedAt, pdfBuffer)],
    resultAvailability: {
      status: "unavailable",
      checkedAt: retrievedAt,
      sourceUrl: null,
      lastCheck: "not_checked",
    },
    schedule: {
      date: parsed.date,
      displayMessage: "Beta schedule",
      matches: selected.matches,
      promotedMatchIds: selected.promotedMatchIds,
    },
  };
}

function failureCode(error){
  const message = String(error?.message || error || "");
  if (/fetch|http|network/i.test(message)) return "fetch_failed";
  if (/document|pdf link|published pdf/i.test(message)) return "document_missing";
  if (/schedule details|no parseable|parse|order of play/i.test(message)) return "parse_failed";
  return "schedule_unavailable";
}

function overviewFallback({ catalogue, now, error }){
  return {
    schemaVersion: jointTennis.SCHEMA_VERSION,
    tournament: cincinnatiTournament(catalogue),
    retrievedAt: now,
    freshness: {
      confidence: "Provisional",
      mode: "overview",
      lastSuccessfulAt: null,
      staleAfterHours: MAX_STALE_HOURS,
      failureCode: failureCode(error),
    },
    sourcePages: Object.values(OFFICIAL_PAGES),
    sourceDocuments: [{
      kind: "order_of_play",
      publisherPageUrl: OFFICIAL_PAGES.order_of_play,
      sourceUrl: OFFICIAL_PAGES.order_of_play,
      retrievedAt: now,
    }],
    resultAvailability: {
      status: "unavailable",
      checkedAt: now,
      sourceUrl: null,
      lastCheck: "not_checked",
    },
    schedule: {
      date: null,
      displayMessage: "Schedule details unavailable",
      matches: [],
      promotedMatchIds: [],
    },
  };
}

function handleRefreshFailure(lastGood, { catalogue, now, error }){
  const lastSuccessfulAt = Date.parse(lastGood?.freshness?.lastSuccessfulAt || "");
  const checkedAt = Date.parse(now);
  const ageHours = (checkedAt - lastSuccessfulAt) / 3600000;
  if (lastGood && Number.isFinite(ageHours) && ageHours >= 0 && ageHours <= MAX_STALE_HOURS && lastGood?.schedule?.matches?.length) {
    const stale = jointTennis.spoilerSafeView(lastGood, true);
    stale.retrievedAt = now;
    stale.freshness = {
      confidence: "Stale",
      mode: "stale_schedule",
      lastSuccessfulAt: lastGood.freshness.lastSuccessfulAt,
      staleAfterHours: MAX_STALE_HOURS,
      ageHours: Number(ageHours.toFixed(2)),
      failureCode: failureCode(error),
    };
    return stale;
  }
  return overviewFallback({ catalogue, now, error });
}

async function checkedFetch(fetchImpl, url, responseType = "text"){
  const response = await fetchImpl(url, {
    headers: { "accept": responseType === "buffer" ? "application/pdf" : "text/html,application/xhtml+xml", "user-agent": "nothingSport-static-refresh/1.0" },
    ...(typeof AbortSignal !== "undefined" && typeof AbortSignal.timeout === "function" ? { signal: AbortSignal.timeout(20000) } : {}),
  });
  if (!response?.ok) throw new Error(`HTTP fetch failed for ${url}: ${response?.status || "unknown"}`);
  if (responseType === "buffer") return Buffer.from(await response.arrayBuffer());
  return response.text();
}

function attachOfficialResults({ pages, document, retainedResults = {}, now }){
  const extracted = {};
  let parsedSourceUrl = null;
  pages.forEach(page => {
    const pageResults = extractOfficialResultsHtml(page.html, {
      document,
      publisherPageUrl: page.pageUrl,
      retrievedAt: now,
    });
    if (Object.keys(pageResults).length) parsedSourceUrl ||= page.pageUrl;
    Object.entries(pageResults).forEach(([matchId, result]) => {
      const existing = extracted[matchId] || retainedResults[matchId];
      if (existing && (existing.score !== result.score || existing.winnerPlayerId !== result.winnerPlayerId)) {
        throw integrityError("conflicting_results", `A newly published Cincinnati result conflicts with the retained result for ${matchId}`);
      }
      extracted[matchId] = result;
    });
  });
  const merged = { ...retainedResults, ...extracted };
  return jointTennis.withResults(document, merged, {
    status: Object.keys(merged).length ? "available" : "unavailable",
    checkedAt: now,
    sourceUrl: parsedSourceUrl,
    lastCheck: Object.keys(extracted).length ? "parsed" : "no_parseable_completed_results",
  });
}

function chooseOrderOfPlayDocument(documents, referenceDate){
  const candidates = documents.filter(document => document.kind === "order_of_play");
  if (!candidates.length) throw new Error("The official Cincinnati Order of Play page published no PDF link");
  const date = new Date(referenceDate || "invalid");
  if (!Number.isFinite(date.valueOf())) return candidates[0];
  // The approved check runs at 9am Sydney, while Cincinnati is still on the
  // prior evening. Prefer the OOP for the Sydney day: it is the upcoming local
  // tournament day that the morning feed needs.
  const [year, month, day] = sydneyDateKey(date).split("-");
  const monthName = Object.keys(MONTHS).find(name => MONTHS[name] === Number(month));
  const score = document => {
    const url = decodeURIComponent(document.sourceUrl).toLowerCase();
    let value = 0;
    if (new RegExp(`${year}[-_/]?${month}[-_/]?${day}`).test(url)) value += 100;
    if (new RegExp(`${monthName.slice(0, 3)}(?:ust)?[-_ ]?0?${Number(day)}(?:\\D|$)`).test(url)) value += 80;
    if (new RegExp(`(?:^|\\D)0?${Number(day)}[-_ ]?${monthName.slice(0, 3)}`).test(url)) value += 80;
    if (url.includes(`/${year}/${month}/`) && new RegExp(`(?:^|\\D)0?${Number(day)}(?:\\D|$)`).test(path.basename(url))) value += 60;
    if (/order|\boop\b|\/op[-_]/.test(url)) value += 10;
    return value;
  };
  return candidates.map((document, index) => ({ document, index, score: score(document) }))
    .sort((first, second) => second.score - first.score || first.index - second.index)[0].document;
}

async function refreshCincinnatiTournament({ fetchImpl = globalThis.fetch, now = new Date().toISOString(), outputPath = OUTPUT_PATH, catalogue = readJson(TENNIS_CATALOGUE_PATH) } = {}){
  if (typeof fetchImpl !== "function") throw new Error("A fetch implementation is required for the Cincinnati refresh");
  const tournament = cincinnatiTournament(catalogue);
  if (!tournamentRefreshIsActive(tournament, now)) return { status: "inactive", changed: false, document: null };
  const previous = fs.existsSync(outputPath) ? readJson(outputPath) : null;
  try {
    const pages = await Promise.all(Object.entries(OFFICIAL_PAGES).map(async ([kind, pageUrl]) => ({ kind, pageUrl, html: await checkedFetch(fetchImpl, pageUrl) })));
    const documents = pages.flatMap(page => discoverPublishedDocuments(page.html, page.pageUrl, page.kind));
    const orderDocument = chooseOrderOfPlayDocument(documents, now);
    const pdfBuffer = await checkedFetch(fetchImpl, orderDocument.sourceUrl, "buffer");
    let document = buildDocumentFromPdf({ pdfBuffer, sourceDocument: orderDocument, retrievedAt: now, catalogue });
    const supportingDocuments = ["tournament_schedule", "draws"].map(kind => documents.find(candidate => candidate.kind === kind)).filter(Boolean);
    document.sourceDocuments = [sourceRecord(orderDocument, now, pdfBuffer), ...supportingDocuments.map(candidate => ({ ...candidate, retrievedAt: now }))];
    const currentMatchIds = new Set(document.schedule.matches.map(match => match.matchId));
    const historicalMatches = [
      ...(previous?.schedule?.matches || []),
      ...(previous?.matchHistory || []),
    ].filter(match => !currentMatchIds.has(match.matchId));
    document.matchHistory = Array.from(new Map(historicalMatches.map(match => [match.matchId, match])).values());
    const addressableMatchIds = new Set([...currentMatchIds, ...document.matchHistory.map(match => match.matchId)]);
    const retainedResults = Object.fromEntries(Object.entries(previous?.resultsByMatchId || {}).filter(([matchId]) => addressableMatchIds.has(matchId)));
    document = attachOfficialResults({ pages, document, retainedResults, now });
    const changed = contentSignature(previous) !== contentSignature(document);
    return { status: "success", changed, document: changed ? document : previous };
  } catch (error) {
    if (String(error?.code || "").startsWith("integrity_")) throw error;
    const document = handleRefreshFailure(previous, { catalogue, now, error });
    const changed = contentSignature(previous) !== contentSignature(document);
    return { status: document.freshness.mode, changed, document: changed ? document : previous, error };
  }
}

function fixtureDocument({ fixturePath, sourceUrl, retrievedAt, catalogue = readJson(TENNIS_CATALOGUE_PATH) }){
  const pdfBuffer = fs.readFileSync(fixturePath);
  return buildDocumentFromPdf({
    pdfBuffer,
    sourceDocument: { kind: "order_of_play", publisherPageUrl: OFFICIAL_PAGES.order_of_play, sourceUrl },
    retrievedAt,
    catalogue,
  });
}

async function main(argv = process.argv.slice(2)){
  const fixtureIndex = argv.indexOf("--fixture");
  if (fixtureIndex >= 0) {
    const fixturePath = path.resolve(argv[fixtureIndex + 1]);
    const retrievedAt = argv[argv.indexOf("--retrieved-at") + 1] || new Date().toISOString();
    const sourceUrl = argv[argv.indexOf("--source-url") + 1] || "https://cincinnatiopen.com/wp-content/uploads/order-of-play-fixture.pdf";
    const document = fixtureDocument({ fixturePath, sourceUrl, retrievedAt });
    if (!argv.includes("--print")) throw new Error("Fixture mode is test-only and requires --print; it cannot overwrite canonical tournament data");
    process.stdout.write(render(document));
    return;
  }
  const result = await refreshCincinnatiTournament();
  if (argv.includes("--probe")) {
    process.stdout.write(`${JSON.stringify({ status: result.status, changed: Boolean(result.changed) })}\n`);
    return;
  }
  if (result.status === "inactive") {
    console.log("Cincinnati tournament refresh inactive; no changes made.");
    return;
  }
  if (!result.changed) {
    console.log("Cincinnati tournament data unchanged; no changes made.");
    return;
  }
  writeOutputs(result.document);
  console.log(`Cincinnati tournament ${result.status} outputs written: ${path.relative(ROOT, OUTPUT_PATH)} and ${path.relative(ROOT, BUNDLE_OUTPUT_PATH)}.`);
}

if (require.main === module) {
  main().catch(error => {
    console.error(error.stack || error.message);
    process.exit(1);
  });
}

