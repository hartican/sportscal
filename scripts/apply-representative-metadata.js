#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const registry = require("../config/representative-events.js");

const inputPath = path.resolve(process.cwd(), process.argv[2] || "data/events.json");
const bundlePath = process.argv[3] ? path.resolve(process.cwd(), process.argv[3]) : null;
const document = JSON.parse(fs.readFileSync(inputPath, "utf8"));
const sourceEvents = Array.isArray(document) ? document : document.events;
if (!Array.isArray(sourceEvents)) throw new Error(`${inputPath} does not contain an event list`);
let applied = 0;
const events = sourceEvents.map(event => {
  const next = registry.applyToEvent(event);
  if (next !== event) applied += 1;
  return next;
});
const expected = Object.keys(registry.metadataByEventId);
const present = new Set(events.map(event => String(event.eventId || event.id)));
const missing = expected.filter(eventId => !present.has(eventId));
if (missing.length) throw new Error(`Explicit Australian representative fixtures missing from ${path.relative(process.cwd(), inputPath)}: ${missing.join(", ")}`);
const output = Array.isArray(document) ? events : { ...document, events };
fs.writeFileSync(inputPath, `${JSON.stringify(output, null, 2)}\n`);
if (bundlePath){
  fs.writeFileSync(bundlePath, `/* Generated by scripts/publish-feed.js and enriched by scripts/apply-representative-metadata.js. Do not edit directly. */\nglobalThis.NOTHINGSPORTS_EVENTS = ${JSON.stringify(events, null, 2)};\n`);
}
console.log(`Applied explicit international/AUS metadata to ${applied} fixtures in ${path.relative(process.cwd(), inputPath)}.`);
