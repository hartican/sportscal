#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const pauses=require('../config/coverage-pauses');
function walk(value){
 if(Array.isArray(value))return value.map(walk);
 if(!value||typeof value!=='object')return value;
 const result=pauses.apply(value);
 for(const key of ['events','fixtures','subEvents'])if(Array.isArray(result[key]))result[key]=result[key].map(walk);
 return result;
}
const files=['feeds/incoming/events.json','data/events.json','data/follow-sources/coverage.v1.json','data/major-events.v1.json','data/chat-fixtures.v1.json'];
for(const dir of ['data/follow-schedule','data/code-inspector'])for(const name of fs.readdirSync(dir))if(name.endsWith('.json'))files.push(`${dir}/${name}`);
for(const file of files){const original=JSON.parse(fs.readFileSync(file));const before=JSON.stringify(original),after=walk(original);if(JSON.stringify(after)!==before)fs.writeFileSync(file,JSON.stringify(after,null,2)+'\n');}
const events=JSON.parse(fs.readFileSync('data/events.json')).events;
fs.writeFileSync('data/events.js',`/* Generated by scripts/publish-feed.js. Do not edit directly. */\nglobalThis.NOTHINGSPORTS_EVENTS = ${JSON.stringify(events,null,2)};\n`);
const knowledgeFile='data/editorial-knowledge.v1.json';const knowledge=JSON.parse(fs.readFileSync(knowledgeFile));
const pausedIds=new Set(files.flatMap(file=>{const data=JSON.parse(fs.readFileSync(file));return (data.events||data.fixtures||[]).filter(pauses.womensT20).flatMap(e=>[e.id,e.eventId,e.canonicalEventId,...(e.sourceEventIds||[])]);}));
knowledge.eventProjections=knowledge.eventProjections.map(p=>({...p,targetIds:p.targetIds.filter(id=>!pausedIds.has(id))})).filter(p=>p.targetIds.length);
fs.writeFileSync(knowledgeFile,JSON.stringify(knowledge,null,2)+'\n');
console.log(`Women's T20 detail coverage paused across publication surfaces (${pausedIds.size} IDs/aliases).`);
