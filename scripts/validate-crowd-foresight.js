'use strict';
const assert=require('node:assert/strict'),c=require('../lib/nsc-crowd');
const now=new Date('2026-09-06T02:00:00Z'),vote=(user,rating,minutes=0,phase='pulse')=>({user_id:user,rating,phase,updated_at:new Date(+now-minutes*60000).toISOString()});
assert.equal(c.summary([vote('a',1,10),vote('a',5),vote('b',3)],{phase:'pulse',now}).average,4);
assert.equal(c.summary([vote('a',5,15)],{phase:'pulse',now}).count,0);
assert.equal(c.summary([vote('a',5,16),vote('b',3)],{phase:'pulse',now}).average,3);
assert.equal(c.summary([vote('a',5),{...vote('model',5),modelled:true}],{phase:'pulse',now}).count,1);
assert.equal(c.summary(Array.from({length:5},(_,i)=>vote(String(i),4)),{phase:'pulse',now}).ranked,true);
assert.equal(c.foresight({prediction:3,outcome:5,benchmark:3,crowdCount:10,forecast:3}).total,2);
assert.equal(c.foresight({prediction:5,outcome:5,benchmark:3.5,crowdCount:10,forecast:3}).total,8);
assert.equal(c.foresight({prediction:2,outcome:2,benchmark:4,crowdCount:10,forecast:4}).total,8);
assert.equal(c.foresight({prediction:5,outcome:5,benchmark:5,crowdCount:10,forecast:5}).total,4);
assert.equal(c.foresight({prediction:5,outcome:5,benchmark:3,crowdCount:4,forecast:3}).total,4);
assert.equal(c.foresight({prediction:5,outcome:2,benchmark:3,crowdCount:20,forecast:3}).total,2);
assert.equal(c.phaseFor({startTimeUtc:'2026-09-06T01:00:00Z',endTimeUtc:'2026-09-06T05:00:00Z'},now),'pulse');
assert.equal(c.phaseFor({status:'completed',startTimeUtc:'2026-09-06T01:00:00Z',endTimeUtc:'2026-09-06T05:00:00Z'},now),'impact');
assert.equal(c.phaseFor({status:'cancelled'},now),null);
console.log('Crowd window, distinct voters, phases and symmetric foresight rules passed.');
const {patchKnown}=require('./quick-results');
const old=[{id:'known',status:'scheduled',startTimeUtc:'2026-09-06T01:00:00Z',sourceCheckedAt:'old'}];
assert.equal(patchKnown(old,[{id:'unknown',status:'completed'}]).count,0,'quick run cannot discover new top-level fixtures');
assert.equal(patchKnown(old,[{...old[0],sourceCheckedAt:'new'}]).count,0,'source-check timestamp is not a content change');
assert.equal(patchKnown(old,[{...old[0],startTimeUtc:'2026-09-06T03:00:00Z'}]).count,1,'kickoff correction preserves identity');

const f1=require('./refresh-f1-results');
