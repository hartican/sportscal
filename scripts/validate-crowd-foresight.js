assert.deepEqual(f1.resultRows('<tbody><tr><td>1</td><td>10</td><td><span>Pierre</span> <span>Gasly</span><span class="md:hidden">GAS</span></td><td>Alpine</td><td>1:22</td><td>1:21</td><td>1:20</td></tr></tbody>')[0].slice(0,4),['1','10','Pierre Gasly','Alpine']);
