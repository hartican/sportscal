'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
function source(){return JSON.parse(fs.readFileSync(path.join(root,'data/canonical/multisession-sports.v1.json'),'utf8'));}
function validate(document=source()){
  const ids=new Set();
  for(const e of document.events){
    if(!e.id||ids.has(e.id)||!e.eventGroupId||!e.sourceUrl?.startsWith('https://')||!Number.isFinite(Date.parse(e.sourceCheckedAt)))throw Error('Invalid multisession source identity or provenance');
    ids.add(e.id);
    if(e.timePrecision==='exact'&&(!Number.isFinite(Date.parse(e.startTimeUtc))||e.timeTbc))throw Error('Invalid exact session timing');
    if(e.timePrecision==='date-only'&&(e.startTimeUtc||e.time))throw Error('Calendar-only session acquired a fabricated clock');
    if(e.key==='supercars'&&(e.date>document.window.endsBefore||e.date<'2026-10-23'))throw Error('Supercars fixture outside approved initial capture horizon');
  }
  return document;
}
function merge(events,document=source()){
  validate(document);const identity=require('../../config/fixture-identity');
  const captured=[...document.events,...require('../../data/canonical/rugby-organised-coverage.v1.json').events].map(e=>identity.normalizeCore({...e,cardKind:'fixture'})),byId=new Map(captured.map(e=>[e.id,e]));
  const aliases=e=>[e.id,e.eventId,e.canonicalEventId,...(e.sourceEventIds||[])].filter(Boolean),targetIds=new Set(captured.flatMap(aliases));
  const selected=events.filter(e=>aliases(e).some(id=>targetIds.has(id))),merged=identity.mergeOverlays(selected,captured),updates=new Map();
  for(const event of merged){const group=byId.get(event.id),value=group?.eventGroupId?{...event,eventGroupId:group.eventGroupId,eventGroupTitle:group.eventGroupTitle,cardKind:'fixture'}:event;for(const id of aliases(event))updates.set(id,value);}
  const seen=new Set(),result=[];
  for(const event of events){const value=aliases(event).map(id=>updates.get(id)).find(Boolean)||event;if(!seen.has(value.id)){result.push(value);seen.add(value.id);}}
  for(const event of merged)if(!seen.has(event.id)){result.push(updates.get(event.id)||event);seen.add(event.id);}
  return result;
}
function apply(){
  const active=e=>require('../../config/cricket-coverage').allowed(e)&&require('../../config/rugby-coverage').allowed(e);
  const archiveFile=path.join(root,'data/canonical/retired-sports-fixtures.v1.json'),archive=fs.existsSync(archiveFile)?JSON.parse(fs.readFileSync(archiveFile,'utf8')):{schemaVersion:'retired-sports-fixtures.v1',events:[]};
  const archived=new Map(archive.events.map(e=>[e.id,e])),today=require('../../config/calendar-export').sydneyDay(new Date());
  for(const name of ['feeds/incoming/events.json','data/events.json']){
    const file=path.join(root,name),d=JSON.parse(fs.readFileSync(file,'utf8')),events=merge(d.events).map(e=>!e.score&&!e.resultStatus&&require('../../config/multisession-events').practice(e)?{...e,resultStatus:'pending',resultSourceUrl:e.sourceUrl,resultSourceCheckedAt:e.sourceCheckedAt}:e);
    for(const event of events)if(!active(event))archived.set(event.id,event);
    d.events=events.filter(e=>active(e)||String(e.endDate||e.date||'9999')<today).map(require('./rugby-artwork').fixture);fs.writeFileSync(file,JSON.stringify(d,null,2)+'\n');
    if(name==='data/events.json'){
      // A local projection retains release stamps. DEPLOY owns publication.
      fs.writeFileSync(path.join(root,'data/events.js'),'/* Generated by scripts/publish-feed.js. Do not edit directly. */\nglobalThis.NOTHINGSPORTS_EVENTS = '+JSON.stringify(d.events,null,2)+';\n');
      const metaFile=path.join(root,'data/feed-meta.json'),meta=JSON.parse(fs.readFileSync(metaFile,'utf8')),utils=require('./feed-utils');
      fs.writeFileSync(metaFile,JSON.stringify({...meta,activeSports:utils.activeSportsFor(d),feedHorizon:utils.summarizeFeedHorizon(d)},null,2)+'\n');
    }
  }
  fs.writeFileSync(archiveFile,JSON.stringify({...archive,events:[...archived.values()].filter(e=>!active(e))},null,2)+'\n');
}
module.exports={source,validate,merge,apply};
