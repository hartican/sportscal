'use strict';
// Existing offline startup builder; only an explicitly owned output is writable.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..'),{setup}=require('./user-state-held-follow-writer-tests');
const digest=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
function run(target){
 assert(target&&path.isAbsolute(target),'an explicitly owned generated output is required');
 const old=fs.readFileSync(path.join(root,'assets/js/app-shell-runtime.js'),'utf8');
 const output=require('../build-app-shell-runtime').build();assert.notEqual(output,old,'changed startup source requires fresh generated bytes');
 const context={};vm.runInNewContext(output,context,{timeout:2000});
 const compiled=context.NOTHINGSPORTS_PROFILE_STORAGE;assert.equal(typeof compiled.preferenceIntentCurrentMatches,'function');
 const oldContext={};vm.runInNewContext(old,oldContext,{timeout:2000});
 const stale=setup();stale.c.PROFILE_STORAGE=oldContext.NOTHINGSPORTS_PROFILE_STORAGE;
 assert.equal(stale.c.setDirectoryEntityFollow('team:football:epl:4','follow'),false,'new inline writer with stale startup bundle must not claim success');
 const cases=[];
 for(const kind of ['new-follow','unsafe-current','wrong-generation','storage-failure','receipt-race']){
  const f=setup(),{c}=f;c.PROFILE_STORAGE=compiled;c.activeProfileBundle=compiled.loadActiveProfile(f.storage);
  if(kind==='unsafe-current')c.userPreferences.theme='night';
  if(kind==='wrong-generation')c.serverStateBaseline.generation++;
  if(kind==='storage-failure')f.storage.setItem=()=>{throw Error('Disposable storage unavailable');};
  let before=JSON.stringify([...f.values]);
  if(kind==='receipt-race')c.PROFILE_STORAGE={...compiled,recordPreferenceIntent(storage,bundle,args){
   const desired=JSON.parse(JSON.stringify(c.userPreferences));desired.preferenceGraph.entityFollows.push({participantId:'team:football:epl:5',followLevel:'follow'});
   compiled.recordPreferenceIntent(storage,bundle,{...args,preferences:desired});before=JSON.stringify([...f.values]);
   return compiled.recordPreferenceIntent(storage,bundle,args);
  }};
  const result=c.setDirectoryEntityFollow('team:football:epl:4','follow');
  if(kind==='new-follow'){
   assert.notEqual(result,false);const bundle=compiled.loadActiveProfile(f.storage),receipt=compiled.readPreferenceIntent(f.storage,bundle,'A');
   assert.equal(receipt.baseUpdatedAt,f.original.baseUpdatedAt);assert.deepEqual(JSON.parse(JSON.stringify(receipt.basePreferences)),f.original.basePreferences);
   for(const id of ['team:football:epl:2','team:football:epl:4'])assert(bundle.entityFollows.some(x=>x.participantId===id&&x.followLevel==='follow'));
  }else{assert.equal(result,false);assert.equal(JSON.stringify([...f.values]),before);}
  cases.push(kind);
 }
 // The builder output is retained outside the immutable input closure. The lane
 // must bind this exact path to its owned-write policy and preserve its receipt.
 fs.writeFileSync(target,output,{flag:'wx'});
 return {scope:'offline generated startup UMD plus actual inline directory writer; no network/browser/private state',cases,staleBundleRejected:true,
  oldRuntimeSha256:digest(old),generatedRuntimeSha256:digest(output),generatedRuntimeBytes:Buffer.byteLength(output),target,
  accountRuntimeChanged:false,sourceShellVersion:'605',productionVersionAllocated:false};
}
module.exports=run;if(require.main===module){try{console.log(JSON.stringify(run(process.argv[2])));}catch(error){console.error(error);process.exitCode=1;}}
