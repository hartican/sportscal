'use strict';
const assert=require('node:assert/strict'),model=require('../config/card-results');
const archive=require('./fixtures/tennis-retirement-display-20261016.json'),fixture=archive.fixture;
assert.equal(archive.sourceSha,'3d8911fd44f31272f624d67d3f0e996bf8c3af96');
assert.match(archive.sourceFeedSha256,/^[a-f0-9]{64}$/);
assert(fixture,'retained retirement fixture required');
assert.deepEqual(fixture.sets,[{away:2,home:5}]);
assert(fixture.resultLabels.includes('Retirement'));
const before=JSON.stringify(fixture),value=model.tennisSets(fixture,fixture.name,{score:fixture.score});
assert(value,'a separately sourced retirement label retains its partial score');
assert.equal(value.status,'Retirement');
assert.deepEqual(value.sets.map(s=>s.scores.map(p=>p.games)),[[5,2]]);
assert.equal(JSON.stringify(fixture),before,'display cannot alter result, winner, source clocks or set evidence');
const unknown={key:'tennis',name:'First Player v Second Player',scoreDisplay:'5–2'};
assert.equal(model.tennisSets(unknown,unknown.name,{score:unknown.scoreDisplay}),null,'an incomplete-looking score alone cannot invent retirement');
assert.equal(model.tennisSets({...unknown,resultLabels:['Completed']},unknown.name,{score:unknown.scoreDisplay}),null,'generic completion is not retirement evidence');
for(const label of ['RET','Retired','Retirement'])assert.equal(model.tennisSets({...unknown,resultLabels:[label]},unknown.name,{score:unknown.scoreDisplay}).status,label);
assert.equal(model.tennisSets({...unknown,scoreDisplay:'5–2 RET'},unknown.name,{score:'5–2 RET'}).status,'RET','existing inline publisher status survives');
const normal={...unknown,scoreDisplay:'6–4, 7–6(5)',resultLabels:['Completed']};
assert.equal(model.tennisSets(normal,normal.name,{score:normal.scoreDisplay}).status,null);
console.log('Tennis terminal display: retained 5–2 retirement, explicit source labels, no inferred retirement, normal sets and immutable evidence passed.');
