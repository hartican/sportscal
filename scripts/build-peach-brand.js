#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const expected='2a0e3a7c2d9096b863ff5d5ca30d65904dc5cd3c152a619d1828e9d3f86eb10b';
const original=fs.readFileSync(path.join(root,'assets/brand/web/nothingsport-logo.png'));
if(crypto.createHash('sha256').update(original).digest('hex')!==expected)throw Error('Original wordmark changed; refusing brand generation');
const shape='M8 58V22H14V14H22V8H42V14H50V22H56V58H42V30H22V58Z';
function logomark(tile=false,inset=0){return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><defs><linearGradient id="peach" x2="0" y2="1"><stop stop-color="#F9BC9B"/><stop offset=".48" stop-color="#FB7B82"/><stop offset="1" stop-color="#FB3D6C"/></linearGradient></defs>${tile?'<path fill="#0C1010" d="M0 0h64v64H0z"/>':''}<path transform="translate(${inset} ${inset}) scale(${1-inset/32})" fill="url(#peach)" d="${shape}"/></svg>`;}
async function build(){
  const sharp=require('sharp'),web=path.join(root,'assets/brand/web'),icons=path.join(root,'icons');
  const catalogue=require('../config/nothingsport-iconography.source');
  const needed=new Set(require('../config/nothingsport-core-icons.json'));
  // Existing renderers own their glyph names. Include every literal caller, while
  // retaining the complete design catalogue separately from the startup payload.
  function scan(folder){for(const entry of fs.readdirSync(folder,{withFileTypes:true})){
    const file=path.join(folder,entry.name);
    if(entry.isDirectory())scan(file);
    else if(/\.(js|html)$/.test(file)&&!/(?:iconography|app-shell-runtime)/.test(file)){
      for(const match of fs.readFileSync(file,'utf8').matchAll(/['"]((?:ui|sport|status|semantic):[a-z0-9-]+)['"]/g))needed.add(match[1]);
    }
  }}
  scan(path.join(root,'config'));scan(path.join(root,'assets/js'));
  for(const match of fs.readFileSync(path.join(root,'index.html'),'utf8').matchAll(/['"]((?:ui|sport|status|semantic):[a-z0-9-]+)['"]/g))needed.add(match[1]);
  const active=Object.fromEntries(Object.entries(catalogue).filter(([key])=>needed.has(key)));
  fs.writeFileSync(path.join(root,'config/nothingsport-iconography.js'),
    '// Generated by scripts/build-peach-brand.js from the complete first-party catalogue.\n'+
    '(function(r){const a=Object.freeze('+JSON.stringify(active)+');r.NOTHINGSPORTS_ICONOGRAPHY=a;if(typeof module==="object"&&module.exports)module.exports=a;})(globalThis);\n');
  fs.writeFileSync(path.join(web,'nothingsport-iconography.svg'),'<svg xmlns="http://www.w3.org/2000/svg"><defs>'+Object.entries(catalogue).map(([key,body])=>`<symbol id="${key.replace(':','-')}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`).join('')+'</defs></svg>');
  fs.writeFileSync(path.join(web,'nothingsport-logomark.svg'),logomark());
  fs.writeFileSync(path.join(icons,'nothingsport-favicon.svg'),logomark(true,4));
  for(const size of [32,180,192,512])await sharp(Buffer.from(logomark(true,5))).resize(size,size).png().toFile(path.join(icons,`nothingsport-app-${size}.png`));
  await sharp(Buffer.from(logomark(true,11))).resize(512,512).png().toFile(path.join(icons,'nothingsport-app-maskable-512.png'));
  await sharp(Buffer.from(logomark(true,5))).resize(720,720).png().toFile(path.join(web,'nothingsport-app-icon.png'));
  if(!original.equals(fs.readFileSync(path.join(web,'nothingsport-logo.png'))))throw Error('Wordmark must remain byte-identical');
  console.log(`Built ${Object.keys(catalogue).length} catalogue icons / ${Object.keys(active).length} active icons, separate logomark and launcher assets; original wordmark SHA-256 unchanged.`);
}
if(require.main===module)build().catch(error=>{console.error(error.message);process.exitCode=1;});
module.exports={logomark,expected};
