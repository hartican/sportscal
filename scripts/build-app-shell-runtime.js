#!/usr/bin/env node
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname,"..");
const paths = require("../config/app-shell-modules.json");
function cardStandings(){
  return fs.readdirSync(path.join(root,'data/canonical')).filter(name=>name.endsWith('.json')).sort()
    .flatMap(name=>JSON.parse(fs.readFileSync(path.join(root,'data/canonical',name),'utf8')).ladderSnapshots||[])
    .map(({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries})=>({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries:entries.map(({participantId,rank})=>({participantId,rank}))}));
}
// Tuples remove repeated wire keys; expand once to preserve the public object contract.
function standingsSource(){
  const packed=cardStandings().map(({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries})=>{
    let prefix=entries[0]?.participantId||'';
    for(const {participantId} of entries)while(!participantId.startsWith(prefix))prefix=prefix.slice(0,-1);
    return [competitionId,seasonLabel,roundLabel,snapshotTimeUtc,prefix,entries.map(({participantId,rank})=>[participantId.slice(prefix.length),rank])];
  });
  return "globalThis.NOTHINGSPORTS_FEED_CARD_STANDINGS="+JSON.stringify(packed)
    + ".map(([competitionId,seasonLabel,roundLabel,snapshotTimeUtc,prefix,entries])=>({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries:entries.map(([participantId,rank])=>({participantId:prefix+participantId,rank}))}));\n";
}
function build(){
  const source = "// Generated by scripts/build-app-shell-runtime.js. Edit the source modules, not this file.\n"
    + standingsSource()
    + paths.map(file => {
      const source = fs.readFileSync(path.join(root,file),"utf8");
      return "\n;/* "+file+" */\n"+source+"\n;";
    }).join("\n");
  // Standard safe compression keeps expanded coverage within the existing
  // startup budget. This browser bundle has no CommonJS loader, so omit Node-only
  // exports and require fallbacks. No property mangling or unsafe transforms.
  return require("terser").minify_sync(source,{compress:{passes:2,global_defs:{module:undefined,require:undefined}},mangle:true,keep_fnames:false,format:{comments:/Generated by/}}).code + "\n";
}
const target = path.join(root,"assets/js/app-shell-runtime.js");
if (require.main === module){
  const output = build();
  if (process.argv.includes("--check")){
    if (!fs.existsSync(target) || fs.readFileSync(target,"utf8") !== output) throw new Error("App shell bundle is stale. Run node scripts/build-app-shell-runtime.js");
  } else { fs.mkdirSync(path.dirname(target),{recursive:true}); fs.writeFileSync(target,output); }
  console.log("App shell runtime: "+paths.length+" modules, "+Buffer.byteLength(output)+" bytes, one request.");
}
module.exports = {build,cardStandings,standingsSource};
