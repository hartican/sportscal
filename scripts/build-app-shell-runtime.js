#!/usr/bin/env node
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname,"..");
const paths = require("../config/app-shell-modules.json");
function cardStandings(){
  return fs.readdirSync(path.join(root,'data/canonical')).filter(name=>name.endsWith('.json')).sort()
    .flatMap(name=>JSON.parse(fs.readFileSync(path.join(root,'data/canonical',name),'utf8')).ladderSnapshots||[])
    .map(({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries})=>({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries:entries.map(({participantId,rank})=>({participantId,rank}))}));
}
function build(){
  const source = "// Generated by scripts/build-app-shell-runtime.js. Edit the source modules, not this file.\n"
    + "globalThis.NOTHINGSPORTS_FEED_CARD_STANDINGS="+JSON.stringify(cardStandings())+";\n"
    + paths.map(file => {
      const source = fs.readFileSync(path.join(root,file),"utf8");
      return "\n;/* "+file+" */\n"+source+"\n;";
    }).join("\n");
  // Parse/print and rename local bindings only; no compression or property mangling.
  return require("terser").minify_sync(source,{compress:false,mangle:true,keep_fnames:true,format:{comments:/Generated by/}}).code + "\n";
}
const target = path.join(root,"assets/js/app-shell-runtime.js");
if (require.main === module){
  const output = build();
  if (process.argv.includes("--check")){
    if (!fs.existsSync(target) || fs.readFileSync(target,"utf8") !== output) throw new Error("App shell bundle is stale. Run node scripts/build-app-shell-runtime.js");
  } else { fs.mkdirSync(path.dirname(target),{recursive:true}); fs.writeFileSync(target,output); }
  console.log("App shell runtime: "+paths.length+" modules, "+Buffer.byteLength(output)+" bytes, one request.");
}
module.exports = {build};
