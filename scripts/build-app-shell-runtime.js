#!/usr/bin/env node
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname,"..");
const paths = require("../config/app-shell-modules.json");
function cardStandings(folder=path.join(root,'data/canonical')){
  return fs.readdirSync(folder).filter(name=>name.endsWith('.json')).sort()
    .flatMap(name=>JSON.parse(fs.readFileSync(path.join(folder,name),'utf8')).ladderSnapshots||[])
    .map(({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries})=>({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries:entries.map(({participantId,rank,sharedRank,rankPending})=>({participantId,rank,...(sharedRank===true?{sharedRank:true}:{}),...(rankPending===true?{rankPending:true}:{})}))}));
}
// Omit the ordinary consecutive rank from the wire; exceptional/shared/pending
// positions retain explicit tuples. Expansion preserves the public contract.
function standingsSource(snapshots=cardStandings()){
  const packed=snapshots.map(({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries})=>{
    let prefix=entries[0]?.participantId||'';
    for(const {participantId} of entries)while(!participantId.startsWith(prefix))prefix=prefix.slice(0,-1);
    return [competitionId,seasonLabel,roundLabel,snapshotTimeUtc,prefix,entries.map(({participantId,rank,sharedRank,rankPending},index)=>{
      const flags=(sharedRank===true?1:0)|(rankPending===true?2:0),id=participantId.slice(prefix.length);
      return rank===index+1&&!flags?id:[id,rank,...(flags?[flags]:[])];
    })];
  });
  return "globalThis.NOTHINGSPORTS_FEED_CARD_STANDINGS="+JSON.stringify(packed)
    + ".map(([competitionId,seasonLabel,roundLabel,snapshotTimeUtc,prefix,entries])=>({competitionId,seasonLabel,roundLabel,snapshotTimeUtc,entries:entries.map((entry,index)=>{const [participantId,rank=index+1,flags=0]=typeof entry==='string'?[entry]:entry;return {participantId:prefix+participantId,rank,...(flags&1?{sharedRank:true}:{}),...(flags&2?{rankPending:true}:{})};})}));\n";
}
function pinnedFixtureEditorial({feed, catalogue, knowledge}={}){
  const read = file => JSON.parse(fs.readFileSync(path.join(root,file), "utf8"));
  feed ||= read("data/events.json");
  catalogue ||= read("data/major-events.v1.json");
  knowledge ||= read("data/editorial-knowledge.v1.json");
  const editorial = require("./lib/editorial-narrative");
  const major = require("../config/major-events");
  const reconciliation = require("../config/feed-fixture-reconciliation");
  const issues = editorial.validateKnowledge(knowledge);
  if (issues.length) throw new Error("Invalid bootstrap editorial provenance: " + issues[0]);
  // Existing pre-canonical legacy pin only; this is not a second fixture feed.
  const id = "major-match:rlwc-2026:australia-new-zealand";
  const parent = catalogue.events.find(event => event.subEvents?.some(child => child.id === id));
  const child = parent?.subEvents.find(child => child.id === id);
  const saved = child && major.fixtureFromSubEvent(child,parent);
  const canonical = saved && reconciliation.canonicalFixtureFor(saved,feed.events);
  const projection = canonical && editorial.projectionForTarget(knowledge,"feed-event",canonical);
  if (!saved || !canonical || !projection) throw new Error("Missing validated existing World Cup bootstrap pin");
  const narrative = editorial.editorialNarrativeFor(projection,editorial.indexesFor(knowledge));
  for (const [field,value] of Object.entries(narrative)) require("node:assert/strict").deepEqual(value,canonical.editorialNarrative?.[field],"Bootstrap must use the validated published projection field " + field);
  // Retain source-owned lifecycle annotations (for example phase) as published.
  return {[id]:{fixtureKey:reconciliation.semanticFixtureKey(canonical),status:canonical.status,editorialNarrative:canonical.editorialNarrative}};
}
function pinnedFixtureEditorialSource(records=pinnedFixtureEditorial()){
  return "globalThis.NOTHINGSPORTS_PINNED_FIXTURE_EDITORIAL=" + JSON.stringify(records) + ";\n";
}

function build(){
  const source = "// Generated by build-app-shell-runtime.js\n"
    + standingsSource()
    + pinnedFixtureEditorialSource()
    + paths.map(file => {
      const source = fs.readFileSync(path.join(root,file),"utf8");
      return "\n;/* "+file+" */\n"+source+"\n;";
    }).join("\n");
  // Standard safe compression keeps expanded coverage within the existing
  // startup budget. This browser bundle has no CommonJS loader, so omit Node-only
  // exports and require fallbacks. Four ordinary passes reduce transferred bytes
  // within the fixed startup budget. No property mangling or unsafe transforms.
  return require("terser").minify_sync(source,{compress:{passes:4,global_defs:{module:undefined,require:undefined}},mangle:true,keep_fnames:false,format:{comments:false}}).code + "\n";
}
const target = path.join(root,"assets/js/app-shell-runtime.js");
if (require.main === module){
  const optionalTarget=path.join(root,'assets/js/calendar-sync-ui.js');
  const optionalOutput=require('terser').minify_sync(fs.readFileSync(path.join(root,'assets/js/calendar-sync-ui.source.js'),'utf8'),{compress:{passes:4},mangle:true}).code+'\n';
  if(process.argv.includes('--check')){if(!fs.existsSync(optionalTarget)||fs.readFileSync(optionalTarget,'utf8')!==optionalOutput)throw Error('Calendar UI bundle is stale');}
  else fs.writeFileSync(optionalTarget,optionalOutput);
  const output = build();
  if (process.argv.includes("--check")){
    if (!fs.existsSync(target) || fs.readFileSync(target,"utf8") !== output) throw new Error("App shell bundle is stale. Run node scripts/build-app-shell-runtime.js");
  } else { fs.mkdirSync(path.dirname(target),{recursive:true}); fs.writeFileSync(target,output); }
  console.log("App shell runtime: "+paths.length+" modules, "+Buffer.byteLength(output)+" bytes, one request.");
}
module.exports = {build,cardStandings,standingsSource,pinnedFixtureEditorial,pinnedFixtureEditorialSource};
